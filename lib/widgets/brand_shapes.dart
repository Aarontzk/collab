/// Shape hiasan: hanya garis tepi bergradasi, tanpa isi.
class DecoShape extends StatelessWidget {
  const DecoShape(
    this.shape, {
    super.key,
    this.size = 120,
    this.strokeWidth = 1.5,
    this.rotation = 0,
    this.opacity = 1,
  });

  final BrandShape shape;
  final double size;
  final double strokeWidth;
  final double rotation;
  final double opacity;

  @override
  Widget build(BuildContext context) => IgnorePointer(
    child: Opacity(
      opacity: opacity,
      child: Transform.rotate(
        angle: rotation,
        child: CustomPaint(
          size: Size.square(size),
          painter: _ShapePainter(shape, strokeWidth),
        ),
      ),
    ),
  );
}

class _ShapePainter extends CustomPainter {
  _ShapePainter(this.shape, this.strokeWidth);

  final BrandShape shape;
  final double strokeWidth;

  @override
  void paint(Canvas canvas, Size size) {
    final scale = size.width / 380;
    final path = shape.path.transform(
      (Matrix4.identity()..scaleByDouble(scale, scale, 1, 1)).storage,
    );
    final paint = Paint()
      ..style = PaintingStyle.stroke
      ..strokeWidth = strokeWidth
      ..shader = brandSweep().createShader(Offset.zero & size);
    canvas.drawPath(path, paint);
  }

  @override
  bool shouldRepaint(_ShapePainter old) =>
      old.shape != shape || old.strokeWidth != strokeWidth;
}

/// Garis tepi kartu bergradasi (dilukis di atas kartu).
class GradientBorderPainter extends CustomPainter {
  const GradientBorderPainter({required this.radius, this.width = 2});

  final double radius;
  final double width;

  @override
  void paint(Canvas canvas, Size size) {
    final rect = (Offset.zero & size).deflate(width / 2);
    final paint = Paint()
      ..style = PaintingStyle.stroke
      ..strokeWidth = width
      ..shader = brandSweep().createShader(Offset.zero & size);
    canvas.drawRRect(
      RRect.fromRectAndRadius(rect, Radius.circular(radius - width / 2)),
      paint,
    );
  }

  @override
  bool shouldRepaint(GradientBorderPainter old) =>
      old.radius != radius || old.width != width;
}

